    <script>
        (function () {
            const form = document.getElementById('contactForm');
            const submitBtn = document.getElementById('submitBtn');

            function showError(id, msg) {
                const el = document.getElementById(id);
                if (!el) return;
                if (msg) {
                    el.textContent = msg;
                    el.classList.remove('hidden');
                } else {
                    el.textContent = '';
                    el.classList.add('hidden');
                }
            }

            function validate() {
                let ok = true;
                const name = form.name.value.trim();
                const email = form.email.value.trim();
                const message = form.message.value.trim();

                if (name.length < 2) { showError('err-name', 'Nama minimal 2 huruf'); ok = false; } else showError('err-name', '');

                const eRe = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
                if (!eRe.test(email)) { showError('err-email', 'Masukkan alamat email valid'); ok = false; } else showError('err-email', '');

                if (message.length < 10) { showError('err-message', 'Tolong tulis pesan minimal 10 karakter'); ok = false; } else showError('err-message', '');

                const hp = form.querySelector('[name="hp_field"]')?.value;
                if (hp && hp.length > 0) { ok = false; }

                return ok;
            }

            form.addEventListener('submit', async function (e) {
                e.preventDefault();

                if (!validate()) {
                    showToast('Periksa kembali data formulir.', 'error');
                    return;
                }

                submitBtn.disabled = true;
                const original = submitBtn.innerHTML;
                submitBtn.innerHTML = '<i class="fas fa-spinner fa-spin mr-2"></i> Mengirim...';

                try {
                    const response = await fetch('api/kontak.php', {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/json' },
                        body: JSON.stringify({
                            nama: form.name.value.trim(),
                            email: form.email.value.trim(),
                            pesan: form.message.value.trim()
                        })
                    });
                    const result = await response.json();
                    if (response.ok) {
                        showToast('Terima kasih! Pesan sudah terkirim.', 'success');
                        form.reset();
                    } else {
                        showToast('Gagal mengirim pesan. Coba lagi nanti.', 'error');
                    }
                } catch (err) {
                    console.error(err);
                    showToast('Gagal mengirim pesan. Coba lagi nanti.', 'error');
                } finally {
                    submitBtn.disabled = false;
                    submitBtn.innerHTML = original;

                }
            });

            document.getElementById('resetBtn')?.addEventListener('click', function () {
                ['err-name', 'err-email', 'err-message'].forEach(id => {
                    const el = document.getElementById(id);
                    if (el) el.classList.add('hidden');
                });
            });
        })();
    </script>
